def _tracked_files() -> list[Path]:
    try:
        proc = subprocess.run(
            ["git", "ls-files", "-z"],
            cwd=REPO,
            capture_output=True,
            check=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return [
            path
            for path in REPO.rglob("*")
            if path.is_file() and not (SKIP_DIRS & set(path.relative_to(REPO).parts))
        ]
    return [REPO / name.decode() for name in proc.stdout.split(b"\0") if name]


def _hits(path: Path) -> list[str]:
    try:
        data = path.read_bytes()
    except OSError:
        return []
    if b"\0" in data:  # binaire : une adresse en clair ne s'y trouve pas
        return []
    found = []
    for offset in range(len(data) - WINDOW + 1):
        if hashlib.sha256(data[offset:offset + WINDOW]).hexdigest() in BANNED_SHA256:
            found.append(f"{path.relative_to(REPO)}@{offset}")
    return found


def test_no_real_wallet_in_tracked_files():
    assert BANNED_SHA256, "liste d'empreintes vide : garde-fou inopérant"
    hits = [hit for path in _tracked_files() for hit in _hits(path)]
    assert not hits, "adresse de wallet réelle recopiée : " + ", ".join(hits)
